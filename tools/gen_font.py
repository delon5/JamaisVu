#!/usr/bin/env python3
"""Rasterise ASCII 0x20-0x7e of a TTF/OTF font into an anti-aliased 8-bit
alpha atlas and emit C source for the in-game menu (plugin/gui/font_data.c).

usage: tools/gen_font.py <font.otf> <name>:<pixel size> [...] > font_data.c
The default build uses Inter (SIL Open Font License 1.1), see
plugin/gui/FONT_LICENSE.txt.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x20, 0x7e


def emit(path, name, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs, data = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        bbox = font.getbbox(ch)  # relative to the drawing origin (top-left of ascent box)
        adv = int(round(font.getlength(ch)))
        w, h = max(0, bbox[2] - bbox[0]), max(0, bbox[3] - bbox[1])
        off = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
            data += img.tobytes()
        glyphs.append((adv, bbox[0], bbox[1], w, h, off))
    out = []
    out.append(f"static const uint8_t {name}_bitmap[{max(1, len(data))}] = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    if not data:
        out.append("  0,")
    out.append("};\n")
    out.append(f"static const FontGlyph {name}_glyphs[{LAST - FIRST + 1}] = {{")
    for code, g in zip(range(FIRST, LAST + 1), glyphs):
        out.append("  {%d, %d, %d, %d, %d, %d}, /* %r */" % (g + (chr(code),)))
    out.append("};\n")
    out.append(f"const Font {name} = {{ {height}, {ascent}, {FIRST}, {LAST}, "
               f"{name}_glyphs, {name}_bitmap }};\n")
    return "\n".join(out)


def main():
    path = sys.argv[1]
    print("/* Generated by tools/gen_font.py from %s. Do not edit. */\n"
          "/* Font: SIL Open Font License 1.1, see FONT_LICENSE.txt */\n"
          % path.split("/")[-1])
    print('#include "font.h"\n')
    for spec in sys.argv[2:]:
        name, size = spec.split(":")
        print(emit(path, name, int(size)))


if __name__ == "__main__":
    main()
